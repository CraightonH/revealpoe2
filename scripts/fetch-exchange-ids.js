// scripts/fetch-exchange-ids.js — refresh the Lineage support → bulk-exchange id map.
//
// Lineage support gems are fungible, fixed items: they are NOT traded as Listed
// Items in the regular item search, but through PoE2's bulk/currency exchange.
// A bulk-exchange deep link needs the item's "want" id (e.g. amanamus-tithe),
// which lives in the official trade service's static data — NOT in RePoE source.
// Like TRADE_LEAGUE, that's volatile trade-service state, so we cache it in a
// committed file (src/data/lineage-exchange-ids.json) and refresh it with this
// script, the same way data is refreshed by a re-scrape.
//
//   node scripts/fetch-exchange-ids.js   (alias: npm run fetch:exchange-ids)
//
// It fetches api/trade2/data/static, pulls the LineageSupportGems group, matches
// each entry to our gem by display name, and writes a { <gem metadata id>:
// <exchange id> } map plus a coverage report (which of our Lineage gems got no
// id, which exchange entries we don't carry yet — i.e. scrape/trade drift).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadJson } from './graph/loader.js';

const STATIC_URL = 'https://www.pathofexile.com/api/trade2/data/static';
const OUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/data/lineage-exchange-ids.json',
);

// Loose key for name matching: case/space-insensitive, curly→straight apostrophe.
function nameKey(s) {
  return (s ?? '').toLowerCase().replace(/[‘’]/g, "'").replace(/\s+/g, ' ').trim();
}

async function fetchStatic() {
  for (let attempt = 1; attempt <= 3; attempt++) {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), 20_000);
    try {
      const r = await fetch(STATIC_URL, {
        headers: { 'User-Agent': 'poe2wiki/fetch-exchange-ids (+https://poe2wiki.pages.dev)' },
        signal: ctrl.signal,
      });
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      return await r.json();
    } catch (err) {
      if (attempt === 3) throw err;
      console.warn(`[exchange-ids] fetch attempt ${attempt} failed (${err.message}); retrying…`);
      await new Promise((res) => setTimeout(res, 1000 * attempt));
    } finally {
      clearTimeout(timer);
    }
  }
}

async function main() {
  const data = await fetchStatic();
  const group = (data.result ?? []).find((g) => (g.id ?? g.label) === 'LineageSupportGems');
  if (!group) throw new Error('LineageSupportGems group not found in trade2/data/static');
  const exchange = group.entries.map((e) => ({ id: e.id, name: e.text }));

  // Our Lineage gems: display name → metadata id, from source (a re-scrape tool
  // is allowed to read source directly; the graph/runtime never does).
  const gems = loadJson('repoe-poe2/skill_gems.json');
  const oursByName = new Map(); // nameKey -> { id, name }
  for (const [id, rec] of Object.entries(gems)) {
    const name = rec?.base_item?.display_name;
    if (!name || name.includes('[DNT')) continue;
    if (!(rec.tags ?? []).includes('lineage')) continue;
    const key = nameKey(name);
    if (!oursByName.has(key)) oursByName.set(key, { id, name });
  }

  const map = {};
  const matchedNames = new Set();
  const unmatchedExchange = [];
  for (const e of exchange) {
    const ours = oursByName.get(nameKey(e.name));
    if (ours) {
      map[ours.id] = e.id;
      matchedNames.add(nameKey(e.name));
    } else {
      unmatchedExchange.push(e.name);
    }
  }
  const ourMissing = [...oursByName.values()]
    .filter((g) => !matchedNames.has(nameKey(g.name)))
    .map((g) => g.name);

  // Deterministic key order so the committed file diffs cleanly between runs.
  const sortedMap = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
  const payload = {
    _comment: 'Generated by scripts/fetch-exchange-ids.js — do not hand-edit. '
      + 'Maps our gem metadata id → PoE2 bulk-exchange "want" id (LineageSupportGems).',
    generated_from: STATIC_URL,
    count: Object.keys(sortedMap).length,
    map: sortedMap,
  };
  fs.writeFileSync(OUT, JSON.stringify(payload, null, 2) + '\n');

  console.log(`[exchange-ids] wrote ${payload.count} mappings → ${path.relative(process.cwd(), OUT)}`);
  console.log(`[exchange-ids] exchange entries: ${exchange.length}; our Lineage gems: ${oursByName.size}`);
  if (ourMissing.length) {
    console.warn(`[exchange-ids] ${ourMissing.length} of our Lineage gems have NO exchange id `
      + `(no trade link — likely not bulk-tradeable, or renamed): ${ourMissing.join(', ')}`);
  }
  if (unmatchedExchange.length) {
    console.warn(`[exchange-ids] ${unmatchedExchange.length} exchange gems we don't carry yet `
      + `(re-scrape to pick up): ${unmatchedExchange.join(', ')}`);
  }
}

main().catch((err) => {
  console.error(`[exchange-ids] failed: ${err.message}`);
  process.exit(1);
});
